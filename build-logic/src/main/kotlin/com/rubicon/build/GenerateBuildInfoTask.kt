package com.rubicon.build

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/** Generates the internal `BuildInfo` object from the project version (D9). */
@CacheableTask
abstract class GenerateBuildInfoTask : DefaultTask() {
    @get:Input
    abstract val version: Property<String>

    @get:Input
    abstract val packageName: Property<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val pkg = packageName.get()
        val dir = outputDirectory.get().asFile.resolve(pkg.replace('.', '/'))
        dir.deleteRecursively()
        dir.mkdirs()
        dir.resolve("BuildInfo.kt").writeText(
            """
            |// Generated by the generateBuildInfo task from the `version` Gradle property. Do not edit.
            |package $pkg
            |
            |internal object BuildInfo {
            |    const val VERSION: String = "${version.get()}"
            |}
            |
            """.trimMargin(),
        )
    }
}
